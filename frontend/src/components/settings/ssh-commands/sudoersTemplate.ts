// sudoersTemplate builds a /etc/sudoers.d/proxcenter body from the sudo
// rules of the orchestrator (GET /api/v1/ssh/sudo-rules, internal/sudo) and
// of the frontend (lib/ssh/sudo), for the profiles the administrator picks.
//
// A restricted profile becomes one Cmnd_Alias: every program ProxCenter runs
// as root for those features, each with its arguments pinned by an anchored
// regular expression (sudo 1.9.10 or later). The migrations profile cannot be
// restricted: the migration pipelines run whole scripts through `sudo sh -c`,
// so it grants everything and the template says it is equivalent to root.

import type { SudoProfile, SudoRule } from '@/lib/ssh/sudo'

const SUDO_USER = 'proxcenter'

const ALIAS: Record<Exclude<SudoProfile, 'migrations'>, string> = {
  'node-ops': 'PXC_NODE_OPS',
  'site-recovery': 'PXC_SITE_RECOVERY',
}

// sudoers reads , : = and \ specially inside a command line. A regular
// expression keeps its own backslashes (\. stays a literal dot), so only the
// three separators are escaped.
function escapeArgs(args: string): string {
  return args.replace(/[,:=]/g, m => `\\${m}`)
}

function commandSpec(rule: SudoRule): string {
  return rule.args === '' ? `${rule.path} ""` : `${rule.path} ${escapeArgs(rule.args)}`
}

/** The rules of one profile, without duplicates (same program and arguments). */
export function profileRules(rules: SudoRule[], profile: SudoProfile): SudoRule[] {
  const seen = new Set<string>()

  return rules.filter(r => {
    if (r.profile !== profile) return false
    const key = `${r.path} ${r.args}`

    if (seen.has(key)) return false
    seen.add(key)

    return true
  })
}

export function buildProfileSudoersTemplate(rules: SudoRule[], profiles: SudoProfile[]): string {
  const lines: string[] = [
    '# /etc/sudoers.d/proxcenter',
    `# Generated by ProxCenter (/settings?tab=ssh-commands), profiles: ${profiles.join(', ') || 'none'}.`,
    '# Needs sudo 1.9.10 or later (regular expressions in arguments).',
    '# Validate with: visudo -c -f /etc/sudoers.d/proxcenter',
    `Defaults:${SUDO_USER} !requiretty`,
    // No env_keep: a variable the account could set would reach the programs
    // run as root (debconf evaluates DEBIAN_FRONTEND as code). The upgrade
    // rule sets it itself, through /usr/bin/env.
    '',
  ]

  for (const profile of profiles) {
    if (profile === 'migrations') continue
    const specs = profileRules(rules, profile).map(commandSpec)

    if (specs.length === 0) continue
    const alias = ALIAS[profile]

    lines.push(`# Profile ${profile}`)
    lines.push(`Cmnd_Alias ${alias} = ${specs.join(', \\\n    ')}`)
    lines.push(`${SUDO_USER} ALL=(root) NOPASSWD: ${alias}`)
    lines.push('')
  }

  if (profiles.includes('migrations')) {
    lines.push('# Profile migrations: the migration pipelines run whole scripts through')
    lines.push('# `sudo sh -c`, so this line grants everything. It is equivalent to root.')
    lines.push(`${SUDO_USER} ALL=(ALL) NOPASSWD: ALL`)
    lines.push('')
  }

  return lines.join('\n')
}

export function buildInstallCommand(body: string): string {
  return `cat > /etc/sudoers.d/proxcenter <<'EOF'\n${body}\nEOF\nchmod 440 /etc/sudoers.d/proxcenter\nvisudo -c -f /etc/sudoers.d/proxcenter`
}

// SETUP_BASH creates the dedicated proxcenter SSH user on a PVE node.
export const SETUP_BASH = `# Run on every PVE node (adapt the public key to yours)
# sudo is not part of a stock PVE install
apt install -y sudo
# --system alone sets the home to /nonexistent, where sshd would look for the key
adduser --system --home /home/proxcenter --shell /bin/bash --group proxcenter
# Also repairs a proxcenter user created earlier without --home
usermod -d /home/proxcenter proxcenter
mkdir -p /home/proxcenter/.ssh
echo "ssh-ed25519 AAAA... proxcenter@your-workstation" >> /home/proxcenter/.ssh/authorized_keys
chown -R proxcenter:proxcenter /home/proxcenter/.ssh
chmod 700 /home/proxcenter/.ssh
chmod 600 /home/proxcenter/.ssh/authorized_keys`
