import { describe, expect, it } from 'vitest'

import { evidenceTranslator } from './evidence'
import { drillEvidenceHtml, utc, type DrillEvidence, type Translate } from './evidencePdf'

const stage = (key: string, status: string, detail = '', started_at = '', ended_at = '') => ({ key, status, detail, started_at, ended_at })

const DRILL: any = {
  id: '6219ae60-7a40-457c-8b67-adf4b2c87eb7',
  status: 'succeeded', phase: 'done', result: 'boot_verified', failed_stage: '', error: '',
  cleanup_state: 'done', cleanup_error: '',
  connection_id: 'c1', node: 'pve1', target_storage: 'CephStoragePool', network_mode: 'link_down', bridge: '',
  source: {
    pbs_id: 'pbs-1', pbs_name: 'PBS', pbs_storage: 'pbs-msp', datastore: 'test-vdc', namespace: 'tenant-msp/vdc',
    backup_type: 'vm', backup_id: '100', backup_time: '2026-09-20T18:51:49Z', vm_name: 'Debian13',
    verify_state: 'ok', verified_at: '2026-09-21T02:00:00Z', archive: 'pbs-msp:backup/vm/100/2026-09-20T18:51:49Z',
  },
  temp_vmid: 109, temp_name: 'drill-100-6219ae60', required_bytes: 0,
  stages: [
    stage('archive_found', 'ok', 'archive listed', '2026-10-18T19:01:00Z', '2026-10-18T19:01:00Z'),
    stage('restore_completed', 'ok', 'restored', '2026-10-18T19:01:00Z', '2026-10-18T19:01:36Z'),
    stage('guest_started', 'ok', 'running', '2026-10-18T19:01:36Z', '2026-10-18T19:01:41Z'),
    stage('guest_agent', 'ok', 'agent answered', '2026-10-18T19:01:41Z', '2026-10-18T19:02:08Z'),
    stage('application_check', 'not_assessed', 'not part of this version'),
  ],
  requested_by: 'test@test.com',
  created_at: '2026-10-18T19:01:00Z', started_at: '2026-10-18T19:01:00Z', finished_at: '2026-10-18T19:02:08Z', cleaned_at: '2026-10-18T19:02:19Z',
}

const EVIDENCE: DrillEvidence = {
  drill: DRILL,
  events: [{ ts: '2026-10-18T19:01:00Z', level: 'warning', stage: 'restore_completed', message: 'a <b>bold</b> message' }],
  restore_task: { upid: 'UPID:x', exit_status: 'OK', log_tail: ['progress 100%', 'password=*** used'] },
}

const META = { clusterName: 'PVE-PROD', generatedAt: '2026-10-18T19:07:30Z', locale: 'en', branding: { brandColor: '#E57000', logoDataUri: 'data:image/png;base64,AAA', appName: '' } }

describe('utc', () => {
  it('prints UTC to the second, and a dash for nothing usable', () => {
    expect(utc('2026-10-18T19:01:00.123Z')).toBe('2026-10-18 19:01:00 UTC')
    expect(utc('')).toBe('-')
    expect(utc('not a date')).toBe('-')
    expect(utc('0001-01-01T00:00:00Z')).toBe('-')
  })
})

describe('drillEvidenceHtml', () => {
  let t: Translate

  it('lays out the verdict, the summary, the stages, the PBS verification, the events and the log', async () => {
    t = await evidenceTranslator('en')
    const html = drillEvidenceHtml(EVIDENCE, META, t)
    expect(html).toContain('<title>Restore drill evidence</title>')
    expect(html).toContain('<span class="badge ok">Boot verified</span>')
    expect(html).toContain('<span class="badge ok">Cleaned up</span>')
    expect(html).toContain('Debian13 (#100)')
    expect(html).toContain('PVE-PROD / pve1 / CephStoragePool')
    expect(html).toContain('VMID 109, drill-100-6219ae60')
    expect(html).toContain('Disconnect all NICs (link_down)')
    expect(html).toContain('2026-09-20 18:51:49 UTC')
    expect(html).toContain('<td class="num">36s</td>')
    expect(html).toContain('<span class="badge muted">Not assessed</span>')
    expect(html).toContain('<tr><th>PBS verification</th><td>Verified</td></tr>')
    expect(html).toContain('[Restore completed] a &lt;b&gt;bold&lt;/b&gt; message')
    expect(html).toContain('<pre class="log">progress 100%\npassword=*** used</pre>')
    expect(html).toContain('exit status OK')
    expect(html).toContain('Generated by ProxCenter on 2026-10-18 19:07:30 UTC. Drill 6219ae60-7a40-457c-8b67-adf4b2c87eb7.')
    expect(html).toContain('src="data:image/png;base64,AAA"')
    expect(html).not.toContain('<b>bold</b>')
  })

  it('names the failing step, the cleanup error, the bridge and the white-label name', async () => {
    t = await evidenceTranslator('en')
    const failed = {
      ...DRILL, status: 'failed', result: 'failed', failed_stage: 'restore_completed', error: 'restore failed: unexpected status',
      cleanup_state: 'failed', cleanup_error: 'VMID 109 is locked', cleaned_at: '', network_mode: 'bridge', bridge: 'vmbr9',
      source: { ...DRILL.source, vm_name: '', verify_state: '' },
    }
    const html = drillEvidenceHtml({ drill: failed }, { ...META, branding: { ...META.branding, appName: 'Acme Cloud', logoDataUri: '' } }, t)
    expect(html).toContain('<span class="badge bad">Failed: restore</span>')
    expect(html).toContain('<div class="alert bad">restore failed: unexpected status</div>')
    expect(html).toContain('Cleanup failed: VMID 109 is locked')
    expect(html).toContain('Isolated bridge (vmbr9)')
    expect(html).toContain('VM 100')
    expect(html).toContain('<tr><th>PBS verification</th><td>Not verified</td></tr>')
    expect(html).toContain('No event recorded')
    expect(html).toContain('No log line recorded.')
    expect(html).toContain('Generated by Acme Cloud')
    expect(html).not.toContain('<img')
  })

  it('reads a cancellation as a warning and a running drill by its status', async () => {
    t = await evidenceTranslator('en')
    const cancelled = drillEvidenceHtml({ drill: { ...DRILL, status: 'cancelled', result: 'cancelled', error: 'cancelled by operator' } }, META, t)
    expect(cancelled).toContain('<span class="badge warn">Cancelled</span>')
    expect(cancelled).toContain('<div class="alert warn">cancelled by operator</div>')
    const running = drillEvidenceHtml({ drill: { ...DRILL, status: 'running', result: '', cleanup_state: 'none', cleaned_at: '' } }, META, t)
    expect(running).toContain('<span class="badge info">Running</span>')
  })

  it('reads a guest without agent as started, OS not verified, and says why', async () => {
    t = await evidenceTranslator('en')
    const html = drillEvidenceHtml({ drill: { ...DRILL, result: 'vm_started' } }, META, t)
    expect(html).toContain('<span class="badge warn">Started, OS not verified</span>')
    expect(html).toContain('<div class="alert warn">No guest agent is configured in this VM')
    expect(html).not.toContain('Boot verified')
  })

  it('names the origin of the drill: its schedule, or a manual start', async () => {
    t = await evidenceTranslator('en')
    expect(drillEvidenceHtml(EVIDENCE, META, t)).toContain('<tr><th>Origin</th><td>Manual</td></tr>')
    const scheduled = drillEvidenceHtml({ drill: { ...DRILL, schedule_id: 's1', schedule_name: 'Nightly <PBS>' } }, META, t)
    expect(scheduled).toContain('<tr><th>Origin</th><td>Nightly &lt;PBS&gt;</td></tr>')
  })

  it('reads a refused drill as a failure with its reason', async () => {
    t = await evidenceTranslator('en')
    const html = drillEvidenceHtml({ drill: { ...DRILL, status: 'refused', result: 'refused', error: 'not enough free space', cleanup_state: 'none', cleaned_at: '' } }, META, t)
    expect(html).toContain('<span class="badge bad">Refused</span>')
    expect(html).toContain('<div class="alert bad">not enough free space</div>')
  })
})

describe('drillEvidenceHtml screenshot', () => {
  const PNG = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg=='
  const captured = { ...DRILL, screenshot_state: 'captured', screenshot_at: '2026-10-18T19:02:00Z', screenshot_error: '' }

  it('embeds the captured console with its UTC time and a caption that keeps it out of the verdict', async () => {
    const t = await evidenceTranslator('en')
    const html = drillEvidenceHtml({ ...EVIDENCE, drill: captured, screenshot: { captured_at: '2026-10-18T19:02:01Z', png_base64: PNG } }, META, t)
    expect(html).toContain('<h2>Screenshot</h2>')
    expect(html).toContain(`<img src="data:image/png;base64,${PNG}" alt="Screenshot">`)
    expect(html).toContain('Captured on 2026-10-18 19:02:01 UTC. Console of the test VM after the stabilization delay. For information only: it is not part of the verdict.')
    expect(html.indexOf('<h2>Screenshot</h2>')).toBeGreaterThan(html.indexOf('<h2>PBS verification</h2>'))
    expect(html.indexOf('<h2>Screenshot</h2>')).toBeLessThan(html.indexOf('<h2>Events</h2>'))
    const fallback = drillEvidenceHtml({ drill: captured, screenshot: { captured_at: '', png_base64: PNG } }, META, t)
    expect(fallback).toContain('Captured on 2026-10-18 19:02:00 UTC.')
  })

  it('never embeds anything but plain base64', async () => {
    const t = await evidenceTranslator('en')
    for (const bad of ['AAA"><script>alert(1)</script>', 'AA AA', '', '==AA']) {
      const html = drillEvidenceHtml({ drill: captured, screenshot: { captured_at: '2026-10-18T19:02:01Z', png_base64: bad } }, META, t)
      expect(html, bad).not.toContain('<figure')
      expect(html, bad).not.toContain('<script>')
      expect(html, bad).toContain('<p class="muted">Screenshot unavailable</p>')
    }
  })

  it('states why there is no screenshot', async () => {
    const t = await evidenceTranslator('en')
    const unavailable = drillEvidenceHtml({ drill: { ...DRILL, screenshot_state: 'unavailable', screenshot_error: 'node <pve1> unreachable' }, screenshot: null }, META, t)
    expect(unavailable).toContain('<p class="muted">Screenshot unavailable: node &lt;pve1&gt; unreachable</p>')
    expect(drillEvidenceHtml({ drill: { ...DRILL, screenshot_state: 'unavailable', screenshot_error: '' } }, META, t))
      .toContain('<p class="muted">Screenshot unavailable</p>')

    const notStarted = { ...DRILL, screenshot_state: '', stages: DRILL.stages.map((s: any) => (s.key === 'guest_started' ? { ...s, status: 'failed' } : s)) }
    expect(drillEvidenceHtml({ drill: notStarted }, META, t)).toContain('<p class="muted">No screenshot: the guest did not start.</p>')

    const older = drillEvidenceHtml({ drill: { ...DRILL, screenshot_state: '' } }, META, t)
    expect(older).not.toContain('<h2>Screenshot</h2>')
  })

  it('is translated in the reader language', async () => {
    const t = await evidenceTranslator('fr')
    const html = drillEvidenceHtml({ drill: captured, screenshot: { captured_at: '2026-10-18T19:02:01Z', png_base64: PNG } }, { ...META, locale: 'fr' }, t)
    expect(html).toContain('Capture d&#39;écran')
    expect(html).toContain('Prise le 2026-10-18 19:02:01 UTC.')
  })
})

describe('evidenceTranslator', () => {
  it('reads the reader locale, fills placeholders, and falls back to English then to the key', async () => {
    const fr = await evidenceTranslator('fr')
    expect(fr('backups.restoreDrills.pdf.title')).toBe("Preuve d'exercice de restauration")
    expect(fr('backups.restoreDrills.pdf.logNote', { node: 'pve1', status: 'OK' })).toContain('nœud pve1, statut de sortie OK')
    expect(fr('backups.restoreDrills.result.failedAt')).toBe('Échec : {stage}')
    const fallback = await evidenceTranslator('xx')
    expect(fallback('backups.restoreDrills.pdf.title')).toBe('Restore drill evidence')
    expect((await evidenceTranslator(undefined))('backups.restoreDrills.missing.key')).toBe('backups.restoreDrills.missing.key')
  })
})
