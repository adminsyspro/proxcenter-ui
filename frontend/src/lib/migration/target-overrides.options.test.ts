/**
 * ui#1330 (MAC), ui#1331 (disk options) and ui#1333 (bulk network table): the
 * parsers the create route runs and the resolution the mappers apply.
 */
import { describe, expect, it } from "vitest"

import {
  customMacs, describeDiskPlan, describeOverrides, diskDriveOptions, isThinStorageType, jobTargetOptions,
  normalizeUnicastMac, parseDiskMappings, parseDiskOptions, parseMacPolicy, parseNetworkMap, parseNicMappings,
  planDiskTargets, resolveNicTarget, targetNicMac,
} from "./target-overrides"

describe("NIC MAC choice (ui#1330)", () => {
  it("keeps the source MAC when no mode is given", () => {
    const r = parseNicMappings([{ index: 0, bridge: "vmbr0" }])
    expect(r).toEqual({ ok: true, value: [{ index: 0, bridge: "vmbr0" }] })
  })

  it("accepts regenerate and a custom MAC, normalised to upper case with colons", () => {
    const r = parseNicMappings([
      { index: 0, bridge: "vmbr0", macMode: "regenerate" },
      { index: 1, bridge: "vmbr0", macMode: "custom", mac: "bc-24-11-aa-bb-cc" },
    ])
    expect(r).toEqual({ ok: true, value: [
      { index: 0, bridge: "vmbr0", macMode: "regenerate" },
      { index: 1, bridge: "vmbr0", macMode: "custom", mac: "BC:24:11:AA:BB:CC" },
    ] })
  })

  it.each([
    [{ macMode: "custom", mac: "01:00:5E:00:00:01" }, "unicast"],
    [{ macMode: "custom", mac: "00:00:00:00:00:00" }, "unicast"],
    [{ macMode: "custom", mac: "BC:24:11" }, "unicast"],
    [{ macMode: "custom" }, "unicast"],
    [{ macMode: "other" }, "macMode must be one of"],
    [{ mac: "BC:24:11:AA:BB:CC" }, "needs macMode"],
  ])("refuses %j", (extra, message) => {
    const r = parseNicMappings([{ index: 0, bridge: "vmbr0", ...extra }])
    expect(r.ok).toBe(false)
    expect(r.ok === false && r.error).toContain(message)
  })

  it("normalizes a unicast MAC and rejects anything else", () => {
    expect(normalizeUnicastMac(" bc:24:11:00:00:01 ")).toBe("BC:24:11:00:00:01")
    expect(normalizeUnicastMac("FF:FF:FF:FF:FF:FF")).toBeNull()
    expect(normalizeUnicastMac(42)).toBeNull()
  })

  it("lists the custom MACs of a NIC list", () => {
    expect(customMacs([{ index: 0, bridge: "a", macMode: "custom", mac: "BC:24:11:00:00:01" }, { index: 1, bridge: "a", macMode: "regenerate" }])).toEqual(["BC:24:11:00:00:01"])
    expect(customMacs(undefined)).toEqual([])
  })

  it("parses the bulk macPolicy", () => {
    expect(parseMacPolicy(undefined)).toEqual({ ok: true, value: undefined })
    expect(parseMacPolicy("keep")).toEqual({ ok: true, value: undefined })
    expect(parseMacPolicy("regenerate")).toEqual({ ok: true, value: "regenerate" })
    expect(parseMacPolicy("random").ok).toBe(false)
  })

  it("resolves the MAC the target NIC gets", () => {
    const src = "00:50:56:01:02:03"
    expect(targetNicMac(src, {})).toBe(src)
    expect(targetNicMac(src, {}, "regenerate")).toBeUndefined()
    expect(targetNicMac(src, { macMode: "regenerate" })).toBeUndefined()
    expect(targetNicMac(src, { macMode: "custom", mac: "BC:24:11:00:00:01" }, "regenerate")).toBe("BC:24:11:00:00:01")
  })

  it("logs the MAC choices with the other overrides", () => {
    expect(describeOverrides({
      nics: [{ index: 0, bridge: "vmbr0", macMode: "custom", mac: "BC:24:11:00:00:01" }, { index: 1, bridge: "vmbr1", macMode: "regenerate" }],
      macPolicy: "regenerate",
    })).toBe("Operator overrides: NICs net0->vmbr0 MAC BC:24:11:00:00:01, net1->vmbr1 new MAC; MAC addresses regenerated by Proxmox")
  })
})

describe("disk options (ui#1331)", () => {
  it("defaults to discard on a thin storage and iothread on a virtio-scsi-single SCSI disk", () => {
    expect(diskDriveOptions({ slot: "scsi0", storageType: "rbd", scsihw: "virtio-scsi-single" })).toBe(",discard=on,iothread=1")
    expect(diskDriveOptions({ slot: "scsi1", storageType: "lvm", scsihw: "virtio-scsi-single" })).toBe(",iothread=1")
    expect(diskDriveOptions({ slot: "scsi0", storageType: "zfspool", scsihw: "virtio-scsi-pci" })).toBe(",discard=on")
  })

  it("never sets iothread on SATA or IDE, nor ssd on VirtIO Block", () => {
    expect(diskDriveOptions({ slot: "sata0", storageType: "dir", scsihw: "virtio-scsi-single", profile: { iothread: true, ssd: true } })).toBe(",discard=on,ssd=1")
    expect(diskDriveOptions({ slot: "ide0", storageType: "lvm", profile: { iothread: true } })).toBe("")
    expect(diskDriveOptions({ slot: "virtio0", storageType: "lvmthin", profile: { ssd: true } })).toBe(",discard=on,iothread=1")
  })

  it("applies the profile, and a disk's own choice over it", () => {
    const profile = { discard: false, iothread: false, ssd: true }
    expect(diskDriveOptions({ slot: "scsi0", storageType: "rbd", scsihw: "virtio-scsi-single", profile })).toBe(",ssd=1")
    expect(diskDriveOptions({ slot: "scsi0", storageType: "rbd", scsihw: "virtio-scsi-single", profile, disk: { discard: true, ssd: false } })).toBe(",discard=on")
  })

  it("tells thin storage types apart", () => {
    for (const t of ["rbd", "zfspool", "lvmthin", "dir", "nfs", "cifs"]) expect(isThinStorageType(t)).toBe(true)
    for (const t of ["lvm", "iscsi", "zfs", "", null, undefined]) expect(isThinStorageType(t)).toBe(false)
  })

  it("parses the job profile", () => {
    expect(parseDiskOptions(undefined)).toEqual({ ok: true, value: undefined })
    expect(parseDiskOptions({})).toEqual({ ok: true, value: undefined })
    expect(parseDiskOptions({ discard: true, ssd: false })).toEqual({ ok: true, value: { discard: true, ssd: false } })
    expect(parseDiskOptions({ iothread: "yes" })).toEqual({ ok: false, error: "diskOptions.iothread must be a boolean" })
    expect(parseDiskOptions([]).ok).toBe(false)
  })

  it("keeps a disk mapping that only sets options, and carries them into the plan", () => {
    const r = parseDiskMappings([{ index: 1, ssd: true }])
    expect(r).toEqual({ ok: true, value: [{ index: 1, ssd: true }] })
    expect(parseDiskMappings([{ index: 0, discard: "on" }])).toEqual({ ok: false, error: "disks[0].discard must be a boolean" })
    const plan = planDiskTargets(["a", "b"], r.ok ? r.value : undefined, "local")
    expect(plan.kept[1].options).toEqual({ ssd: true })
    expect(plan.kept[0].options).toBeUndefined()
    expect(describeDiskPlan(plan, "local")).toBe("Per-disk choices: options disk 2->ssd on")
  })
})

describe("bulk network table (ui#1333)", () => {
  it("parses rows of source network, bridge and optional tag", () => {
    expect(parseNetworkMap([{ source: " VM Network ", bridge: "vmbr1", vlanTag: "20" }, { source: "DMZ", bridge: "vnetdmz" }])).toEqual({
      ok: true, value: [{ source: "VM Network", bridge: "vmbr1", vlanTag: 20 }, { source: "DMZ", bridge: "vnetdmz" }],
    })
    expect(parseNetworkMap([])).toEqual({ ok: true, value: undefined })
  })

  it.each([
    ["not an array", {}],
    ["a duplicate source", [{ source: "A", bridge: "vmbr0" }, { source: "A", bridge: "vmbr1" }]],
    ["a bad bridge", [{ source: "A", bridge: "vmbr0;rm" }]],
    ["an empty source", [{ source: "", bridge: "vmbr0" }]],
    ["a bad tag", [{ source: "A", bridge: "vmbr0", vlanTag: 5000 }]],
    ["a non-object row", ["A"]],
  ])("refuses %s", (_label, raw) => {
    expect(parseNetworkMap(raw).ok).toBe(false)
  })

  it("resolves a NIC: its own mapping, then its network's row, then the defaults", () => {
    const map = [{ source: "DMZ", bridge: "vnetdmz", vlanTag: 30 }]
    const defaults = { bridge: "vmbr0", vlanTag: 10 }
    expect(resolveNicTarget(0, undefined, defaults, { name: "DMZ", map })).toEqual({ bridge: "vnetdmz", vlanTag: 30 })
    expect(resolveNicTarget(0, undefined, defaults, { name: "LAN", map })).toEqual({ bridge: "vmbr0", vlanTag: 10 })
    expect(resolveNicTarget(0, [{ index: 0, bridge: "vmbr9" }], defaults, { name: "DMZ", map })).toMatchObject({ bridge: "vmbr9", vlanTag: 10 })
  })

  it("logs the table", () => {
    expect(describeOverrides({ networkMap: [{ source: "DMZ", bridge: "vnetdmz", vlanTag: 30 }] })).toBe('Operator overrides: networks "DMZ"->vnetdmz tag 30')
  })
})

describe("jobTargetOptions", () => {
  it("keeps the persisted options and drops malformed ones", () => {
    expect(jobTargetOptions({ networkMap: [{ source: "A", bridge: "vmbr0" }], macPolicy: "regenerate", diskOptions: { ssd: true } }))
      .toEqual({ networkMap: [{ source: "A", bridge: "vmbr0" }], macPolicy: "regenerate", diskOptions: { ssd: true } })
    expect(jobTargetOptions({ networkMap: [], macPolicy: "keep", diskOptions: [] })).toEqual({})
  })
})
